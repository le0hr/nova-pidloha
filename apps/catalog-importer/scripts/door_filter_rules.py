def color_family(name):
    if not name: return None
    outer = re.split(r"/|\+|,", name)[0]  # outer side; drop moulding/edge/handle notes
    outer = re.sub(r"\(.*?\)|\S+ ручка", " ", outer).lower()
    for family, rx in COLOR_RULES:
        if re.search(rx, outer): return family
    return None

def glass_family(name):
    if not name: return None
    n = name.lower().strip()
    for family, rx in GLASS_RULES:
        if re.search(rx, n): return family
    return None

EDGE_RULES = [
    ("Алюмінієва чорна", r"чорн\w* алюмін|алюмін\w* чорн"),
    ("Алюмінієва сіра", r"сір\w* алюмін|алюмін\w* сір"),
    ("Алюмінієва", r"алюмін"),
    ("Чорна матова", r"чорна"),
    ("Звичайна", r"звичайна"),
]

def edge_family(name):
    n = (name or "").lower()
    for family, rx in EDGE_RULES:
        if n and re.search(rx, n): return family
    return None

def coating(name):
    return COATING.get((name or "").strip().lower())
